"""Export Shiller's monthly real returns for the in-browser simulator.

    python export_web.py          write docs/history.js
    python export_web.py --open   ...and open the web app in a browser

The page loads history.js with a <script> tag (not fetch), so docs/index.html
also works opened straight from disk.
"""
from __future__ import annotations

import argparse
import json
import webbrowser
from pathlib import Path

import data

ROOT = Path(__file__).parent
OUT = ROOT / "docs" / "history.js"


def export(refresh: bool = False) -> Path:
    hist = data.load_returns(1871, refresh=refresh)
    payload = {
        "start": f"{hist.index[0]:%Y-%m}",
        "end": f"{hist.index[-1]:%Y-%m}",
        "stocks": hist["stocks"].round(6).tolist(),
        "bonds": hist["bonds"].round(6).tolist(),
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("// Generated by export_web.py from Robert Shiller's data: monthly real total\n"
                   "// returns (stocks = S&P Composite, bonds = 10-year Treasury), CPI-deflated.\n"
                   f"window.MC_HISTORY = {json.dumps(payload, separators=(',', ':'))};\n")
    print(f"{OUT.relative_to(ROOT)}: {len(hist)} months, {payload['start']} to {payload['end']}")
    return OUT


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--open", action="store_true", help="open docs/index.html afterwards")
    ap.add_argument("--refresh", action="store_true", help="re-download Shiller's data first")
    args = ap.parse_args()
    export(args.refresh)
    if args.open:
        webbrowser.open((ROOT / "docs" / "index.html").as_uri())


if __name__ == "__main__":
    main()
